def get_language_switch_copy(language="en"):
    """Return the label and tooltip for switching away from the current language."""
    return LANGUAGE_SWITCH_COPY.get(language, LANGUAGE_SWITCH_COPY["en"])


def translate_text(value, language="en"):
    """Translate an interface string while leaving user and database data untouched."""
    if language != "zh" or not isinstance(value, str):
        return value
    if value in ZH_TRANSLATIONS:
        return ZH_TRANSLATIONS[value]

    dynamic_patterns = [
        (r"Page (\d+) / (\d+)", lambda m: f"第 {m.group(1)} 页 / 共 {m.group(2)} 页"),
        (
            r"Showing (\d+)-(\d+) of (\d+) result\(s\)\.",
            lambda m: f"显示第 {m.group(1)}–{m.group(2)} 条，共 {m.group(3)} 条。",
        ),
        (
            r"(\d+) of (\d+) queries matched · (\d+) not found · (\d+) result row\(s\)\.",
            lambda m: (
                f"{m.group(2)} 个输入项中已匹配 {m.group(1)} 个 · "
                f"未查到 {m.group(3)} 个 · 共 {m.group(4)} 行结果"
            ),
        ),
        (
            r"(\d+) of (\d+) pairs matched · (\d+) issue\(s\)\.",
            lambda m: (
                f"{m.group(2)} 对中有 {m.group(1)} 对对应正确 · "
                f"{m.group(3)} 项需检查"
            ),
        ),
        (r"([\d,]+) records", lambda m: f"{m.group(1)} 条记录"),
        (
            r"([\d,]+) result\(s\) copied to clipboard\.",
            lambda m: f"已将 {m.group(1)} 条结果复制到剪贴板。",
        ),
        (r"CSV saved to: (.+)", lambda m: f"CSV 已保存至：{m.group(1)}"),
        (
            r"(.+) total abundance  ·  (\d+) genera",
            lambda m: f"总丰度 {m.group(1)}  ·  {m.group(2)} 个属",
        ),
        (r"Duplicate of #(\d+)", lambda m: f"与第 {m.group(1)} 行重复"),
        (r"Edit (.+)", lambda m: f"编辑 {m.group(1)}"),
        (
            r"Version (.+)  ·  © All rights reserved by the authors",
            lambda m: f"版本 {m.group(1)}  ·  © 作者保留所有权利",
        ),
    ]
    for pattern, formatter in dynamic_patterns:
        match = re.fullmatch(pattern, value)
        if match:
            return formatter(match)
    return value
